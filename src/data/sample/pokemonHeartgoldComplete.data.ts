// 브케인 스타팅 기준. 연두마을 → 성도 8배지 → 리그 1차 → 관동 8배지 → 은빛산 레드 전 구간.

// ─── 타입 정의 ───────────────────────────────────────────────────
export interface PartySlot {
  pokemonId: number
  pokemon: string
  catchTiming: string
  role: string
  keyMoves: string[]
}

export interface HmRow {
  hm: string
  move: string
  holder: string
  obtainedAt: string
  battleValue: string
}

export interface TmRow {
  tm: string
  move: string
  target: string
  judgment: string
}

export interface LevelMilestone {
  pokemonId: number
  pokemon: string
  level: number
  event: string
}

export interface Phase {
  num: number
  title: string
  tasks: string[]
  catches?: string[]
  hm?: string[]
  boss?: {
    name: string
    party: string
    lead: string
    tip?: string
  }
  levelGoal?: string
  checklist: string[]
}

export interface BossRow {
  opponent: string
  opponentId?: number
  lead: string
  tip?: string
}

export interface BossSection {
  title: string
  note: string
  rows: BossRow[]
}

export interface MovePhase {
  phase: string
  moves: string[]
  note?: string
}

export interface FinalMoveset {
  pokemonId: number
  pokemon: string
  phases: MovePhase[]
  avoidTMs?: string[]
}

export interface Alternative {
  pokemonId: number
  pokemon: string
  replaces: string
  catchTiming: string
  pro: string
  con: string
}

export interface ImportantItem {
  timing: string
  location: string
  target: string
  importance: string
  reason: string
}

export interface StarterPick {
  pokemonId: number
  pokemon: string
  team: string[]
  summary: string
}

export interface CandidateRow {
  pokemon: string
  pokemonId: number
  verdict: 'best' | 'good' | 'ok'
  summary: string
}

