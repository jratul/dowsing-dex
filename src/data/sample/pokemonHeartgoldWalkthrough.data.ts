export interface WalkthroughCatch {
  pokemonId: number
  pokemon: string
  location: string
  timing: string
  note: string
  priority: 'star' | 'normal'
}

export interface WalkthroughKeyItem {
  item: string
  from: string
  note?: string
}

export interface WalkthroughBossRow {
  opponent: string
  answer: string
  /** 관장이 가장 먼저 내보내는 포켓몬. HGSS는 트레이너 파티가 순서까지 고정이라 항상 같다. */
  lead?: boolean
}

export interface WalkthroughBoss {
  leader: string
  gym: string
  gymType: string
  levels: string
  note: string
  rows: WalkthroughBossRow[]
  badge: string
}

export interface WalkthroughPhase {
  id: string
  title: string
  subtitle: string
  levelRange: string
  todos: string[]
  catches?: WalkthroughCatch[]
  keyItems?: WalkthroughKeyItem[]
  boss?: WalkthroughBoss
  /** 관동처럼 한 구간에서 체육관을 연속으로 도는 경우. boss 대신 이쪽을 쓴다. */
  bosses?: WalkthroughBoss[]
}

